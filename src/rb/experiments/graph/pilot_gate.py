"""
Protocol 004 section 8's pilot gate, as a command.

WHY THIS EXISTS. `results/004/pilot-extraction-score.json` decides whether the full extraction run
is purchased, and entry 004 renders it into a generated block. It was written by an ad-hoc script
that no longer exists, so a table marked "generated by scripts/sync-004-results.mjs" was reading
from a file nothing in the repository could regenerate. That is the same defect class as 003's
arms-summary.json, which had no producer and carried a retracted number for weeks.

Reads the extraction cache. Does not call the API: the pilot's 100 passages were extracted under
DOC_REASONING and are committed, so the gate replays for free and cannot silently re-buy a
different answer than the one it registered.
"""

import json
from pathlib import Path

from rb.experiments.graph import extraction_score as es
from rb.experiments.graph import llm_extractor as llm
from rb.experiments.graph.extractor import extract_many as spacy_many

ROOT = Path(__file__).resolve().parents[4]
SAMPLE = ROOT / "results" / "003" / "extraction-sample.jsonl"
OUT = ROOT / "results" / "004" / "pilot-extraction-score.json"

# Registered in protocol 004 section 8 BEFORE the pilot ran: spaCy's micro-F1 on this sample plus
# five points absolute. A literal because it is a pre-registered threshold; recomputing it from
# the outcome would make it not a threshold.
BAR_F1 = 0.7203
SPACY_F1 = 0.6703


def run() -> dict:
    rows = [json.loads(l) for l in SAMPLE.read_text().splitlines()]
    gold = {r["doc_id"]: r["entities"] for r in rows}
    texts = {r["doc_id"]: r["text"] for r in rows}

    predicted = llm.extract_many(texts, offline=True, reasoning=llm.DOC_REASONING)
    diagnostic = es.score(gold, predicted, rows=rows)
    micro = diagnostic["micro"]

    # spaCy on the same sample, recomputed rather than quoted, so the two sides of the gate come
    # from the same run of the same scorer.
    spacy_micro = es.score(gold, spacy_many(texts), rows=rows)["micro"]

    return {
        "gate": "protocol-004 section 8",
        "bar_f1": BAR_F1,
        "spacy_f1": SPACY_F1,
        "spacy_f1_recomputed": spacy_micro["f1"],
        "llm": micro,
        "delta_f1": round(micro["f1"] - SPACY_F1, 4),
        "passed": bool(micro["f1"] > BAR_F1),
        "diagnostic": diagnostic,
    }


if __name__ == "__main__":
    r = run()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(r, indent=2) + "\n")
    print(json.dumps({k: v for k, v in r.items() if k != "diagnostic"}, indent=2))
